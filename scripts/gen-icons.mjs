#!/usr/bin/env node
// Renders the logo: design/logo.svg, public/favicon.svg and the Android launcher icons (legacy, round, adaptive foreground
// and monochrome) from one glyph. Needs playwright + chromium. Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { BRAND, PARTS, svgs, glyphMarkup, splashSvg } from './brand.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const res = join(root, 'android/app/src/main/res');
const T = { light: { bg: '#F4F5F6' }, dark: { bg: '#0B0E11' } };   // Smith DS v1 backgrounds (also src/styles/tokens.css)
const accent = BRAND.tile;

/* All geometry lives in scripts/brand.mjs (traced from the approved reference). This script only writes files. */
const px = (svgText, n) => svgText.replace('<svg ', `<svg width="${n}" height="${n}" `);
// legacy launcher (pre-Android 8): rounded tile with a small margin, as launchers draw it as is
const legacy = n => px(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><g transform="translate(512 512) scale(.92) translate(-512 -512)"><rect width="1024" height="1024" rx="${BRAND.radius}" fill="${BRAND.tile}"/>${glyphMarkup()}</g></svg>`, n);
export const parts = { legacy, round: n => px(svgs.round(), n), glyph: n => px(svgs.foreground(), n), mono: n => px(svgs.monochrome(), n) };

mkdirSync(join(root, 'public'), { recursive: true });
const DESIGN = { 'logo.svg': svgs.logo(), 'logo-glyph.svg': svgs.glyph(), 'logo-mono.svg': svgs.mono(), 'logo-mark.svg': svgs.mark(),
  'logo-foreground.svg': svgs.foreground(), 'logo-background.svg': svgs.background(), 'logo-round.svg': svgs.round() };
for (const [f, c] of Object.entries(DESIGN)) writeFileSync(join(root, 'design', f), c);
writeFileSync(join(root, 'public/favicon.svg'), svgs.logo());
// the in-app mark (src/ui/brand.ts) and the start screen (index.html) use the same geometry
writeFileSync(join(root, 'src/brand-art.ts'), `// Generated by scripts/gen-icons.mjs from scripts/brand.mjs. Do not edit.\nexport const TILE = '${BRAND.tile}';\nexport const RADIUS = ${BRAND.radius};\nexport const PART_PATHS: readonly string[] = ${JSON.stringify(PARTS.map(p => p.d))};\n`);
const indexFile = join(root, 'index.html');
writeFileSync(indexFile, readFileSync(indexFile, 'utf8').replace(/<!-- splash-art:start -->[\s\S]*?<!-- splash-art:end -->/, `<!-- splash-art:start -->${splashSvg()}<!-- splash-art:end -->`));

const DENS = { mdpi: [48, 108], hdpi: [72, 162], xhdpi: [96, 216], xxhdpi: [144, 324], xxxhdpi: [192, 432] };
const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });
async function png(markup, px, file) {
  await page.setViewportSize({ width: px, height: px });
  await page.setContent(`<style>html,body{margin:0;background:transparent}</style>${markup}`);
  writeFileSync(file, await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: px, height: px } }));
}
for (const [d, [legacyPx, adaptivePx]] of Object.entries(DENS)) {
  const dir = join(res, `mipmap-${d}`); mkdirSync(dir, { recursive: true });
  await png(parts.legacy(legacyPx), legacyPx, join(dir, 'ic_launcher.png'));
  await png(parts.round(legacyPx), legacyPx, join(dir, 'ic_launcher_round.png'));
  await png(parts.glyph(adaptivePx), adaptivePx, join(dir, 'ic_launcher_foreground.png'));
  await png(parts.mono(adaptivePx), adaptivePx, join(dir, 'ic_launcher_monochrome.png'));
}
await png(parts.legacy(512), 512, join(root, 'design/logo-512.png'));
await browser.close();

// adaptive icons: background colour, the glyph, and a monochrome layer for themed icons (Android 13+)
for (const name of ['ic_launcher', 'ic_launcher_round']) {
  writeFileSync(join(res, `mipmap-anydpi-v26/${name}.xml`), `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
`);
}
writeFileSync(join(res, 'values/ic_launcher_background.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${accent}</color>\n</resources>\n`);

// the stock Capacitor vector foreground is not used by the adaptive icon (it points at the mipmap layers): remove it
const stock = join(res, 'drawable-v24/ic_launcher_foreground.xml'); if (existsSync(stock)) rmSync(stock);
// Splash: a flat colour that matches the theme and an empty system-splash icon, so the web start screen is the only logo on show.
writeFileSync(join(res, 'drawable/splash_icon_empty.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n    <size android:width="1dp" android:height="1dp"/>\n    <solid android:color="#00000000"/>\n</shape>\n`);
for (const d of readdirSync(res).filter(n => n.startsWith('drawable'))) {
  const f = join(res, d, 'splash.png'); if (existsSync(f)) rmSync(f);
}
writeFileSync(join(res, 'drawable/splash.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<color xmlns:android="http://schemas.android.com/apk/res/android" android:color="@color/splash_bg" />\n`);
writeFileSync(join(res, 'values/colors_splash.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="splash_bg">${T.light.bg}</color>\n</resources>\n`);
mkdirSync(join(res, 'values-night'), { recursive: true });
writeFileSync(join(res, 'values-night/colors_splash.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="splash_bg">${T.dark.bg}</color>\n</resources>\n`);
console.log('logo, favicon and launcher icons written');
